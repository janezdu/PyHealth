"""Two hospitals, three panels: what they are, what local training makes, what
FedLIBRA makes.

Reads the coordinates ``eda_embed_projection.py`` already wrote. Nothing is
recomputed and nothing is re-sampled, so this figure and the grid figure show
the SAME points in the SAME PCA basis -- the one fitted on the 8,509 real
pooled train patients. Re-running the projection would redraw the synthetic
sample and the two figures would quietly disagree.

The grid answers "did this arm move toward its own site?", one panel at a
time. This asks what the grid can only be read for sideways: do the two
hospitals stay APART? Colour carries hospital; the arm is the panel.

WHY THIS PAIR. Their real recording depth differs 3.6x -- 2.44 codes per
patient at 277 against 8.88 at 429, on the 478-code scored pool. If a method
preserves what distinguishes two hospitals, these two are where it shows.

READ THE CODES-PER-PATIENT TABLE THIS PRINTS, not the overlap. Two clouds
that overlap in a 2D projection of a 478-dimensional binary space need not be
the same distribution; the printed number is computed in the full space.

Example:
    python examples/fedpyhealth/scripts/fig_two_sites_triptych.py \\
        --json _outputs/results/eda_embed_277_429.json \\
        --out _outputs/results/two_sites_triptych.png
"""
from __future__ import annotations

import argparse
import json
import os

#: Categorical slots 1 and 2 of the validated reference palette. Two series in
#: a scatter clear the all-pairs separation floors with room to spare, which
#: eight slots do not.
HUES = ["#2a78d6", "#eb6834"]
INK, MUTED, LINE = "#1A1D20", "#6E7377", "#D8DDE1"


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--json", default="_outputs/results/eda_embed_277_429.json",
                   help="payload written by eda_embed_projection.py")
    p.add_argument("--panels", default="real,local,fedavg_irm_xm",
                   help="arm keys, left to right; 'real' is the real fold")
    p.add_argument("--labels",
                   default="real patients,"
                           "synthetic patients generated with local-only,"
                           "synthetic patients generated by FedLIBRA",
                   help="panel titles, matching --panels. Commas separate "
                        "panels, so a title cannot contain one.")
    p.add_argument("--real-key", default="real",
                   help="which --panels entry holds REAL patients. It is "
                        "drawn with a different marker: the real fold is the "
                        "target, not another arm, and one shape for both "
                        "invites the reader to compare them as peers.")
    p.add_argument("--per-row", type=int, default=0,
                   help="panels per row; 0 = all in one row. A short last "
                        "row is centred under the one above.")
    p.add_argument("--point-size", type=float, default=17.0)
    p.add_argument("--out", default="_outputs/results/two_sites_triptych.png")
    a = p.parse_args(argv)

    d = json.load(open(a.json))
    sites = d["hospitals"]
    keys = [k.strip() for k in a.panels.split(",")]
    labels = [s.strip() for s in a.labels.split(",")]
    if len(labels) != len(keys):
        raise SystemExit("--labels must have as many entries as --panels")
    for k in keys:
        for h in sites:
            if k not in d["coords"][h]:
                raise SystemExit(
                    f"{a.json} has no arm {k!r} for hospital {h}. "
                    f"Available: {sorted(d['coords'][h])}")

    cpp = {k: {h: d["stats"][h][k]["codes_per_patient"] for h in sites}
           for k in keys}
    print(f"{d['n_pool']} codes in the {d['code_pool']} pool, "
          f"{d['method']} fitted on {d['fit_on']}, fold {d['fold']}")
    print(f"\n{'panel':<18}" + "".join(f"{'hosp ' + h:>16}" for h in sites))
    for k, lab in zip(keys, labels):
        print(f"  {lab:<16}" + "".join(
            f"{cpp[k][h]:>11.2f} c/pt" for h in sites))

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    # One frame for every panel, so a genuinely tighter cloud looks tighter
    # instead of being rescaled into the same box. Equal aspect, but x and y
    # each fit their own range -- a square frame leaves a band of empty space.
    xs = [pt[0] for k in keys for h in sites for pt in d["coords"][h][k]]
    ys = [pt[1] for k in keys for h in sites for pt in d["coords"][h][k]]
    cx, cy = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
    hx = (max(xs) - min(xs)) / 2 * 1.04
    hy = (max(ys) - min(ys)) / 2 * 1.04 + 0.06 * hx   # headroom for the legend

    per = a.per_row or len(keys)
    nrow = -(-len(keys) // per)
    fig = plt.figure(figsize=(4.4 * per, (4.4 * hy / hx + 0.6) * nrow))
    # Two grid columns per panel, so a short last row can shift by half a
    # panel and sit centred.
    gs = fig.add_gridspec(nrow, 2 * per)
    axes = []
    for i in range(len(keys)):
        r, c = divmod(i, per)
        off = per - min(per, len(keys) - r * per)   # empty slots in this row
        axes.append(fig.add_subplot(gs[r, 2 * c + off:2 * c + off + 2]))
    for ax, k, lab in zip(axes, keys, labels):
        is_real = k == a.real_key
        for h, hue in zip(sites, HUES):
            pts = d["coords"][h][k]
            # Diamonds sit lighter than circles at equal area, so the real
            # panel gets a size bump to stay visually level with the others.
            ax.scatter([q[0] for q in pts], [q[1] for q in pts],
                       s=a.point_size * (1.55 if is_real else 1.0), c=hue,
                       marker="D" if is_real else "o", linewidths=0,
                       alpha=0.75 if is_real else 0.55,
                       label=f"Hospital {h}")
        ax.set_xlim(cx - hx, cx + hx); ax.set_ylim(cy - hy + 0.06 * hx, cy + hy + 0.06 * hx)
        ax.set_aspect("equal", adjustable="box")
        ax.set_xticks([]); ax.set_yticks([])
        ax.set_title(lab, fontsize=11, color=INK, pad=8, wrap=True)
        ax.legend(loc="upper left", frameon=False, fontsize=8.5,
                  markerscale=1.6, handletextpad=0.3, borderpad=0.2)
        for sp in ax.spines.values():
            sp.set_color(LINE)

    fig.tight_layout()
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    fig.savefig(a.out, dpi=220, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    print(f"\nwrote {a.out}")


if __name__ == "__main__":
    main()
